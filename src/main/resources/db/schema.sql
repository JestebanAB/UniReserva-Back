-- ---------- Usuarios y autenticación (mismo patrón de Razonando) ----------
CREATE TABLE IF NOT EXISTS roles (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(50) NOT NULL UNIQUE,
    name_showed  VARCHAR(50) NOT NULL,
    description  TEXT
);

CREATE TABLE IF NOT EXISTS users (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_type        VARCHAR(50)  NOT NULL,
    id_number      VARCHAR(15)  NOT NULL UNIQUE,
    names          VARCHAR(80)  NOT NULL,
    surnames       VARCHAR(80)  NOT NULL,
    nickname       VARCHAR(50)  UNIQUE,
    email          VARCHAR(80)  NOT NULL UNIQUE,
    state          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    creation_date  TIMESTAMP    NOT NULL DEFAULT now(),
    photo_url      VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS users_roles (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role_id  BIGINT NOT NULL REFERENCES roles(id),
    UNIQUE (user_id, role_id)
);

CREATE TABLE IF NOT EXISTS auth (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT REFERENCES users(id) ON DELETE CASCADE,
    supplier     VARCHAR(50) NOT NULL,
    supplier_id  VARCHAR(50),
    pass_hash    VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    id          UUID PRIMARY KEY,
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at  TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX IF NOT EXISTS auth_sessions_user_id_idx    ON auth_sessions (user_id);
CREATE INDEX IF NOT EXISTS auth_sessions_expires_at_idx ON auth_sessions (expires_at);

-- ---------- Dominio: recursos y reservas ----------
CREATE TABLE IF NOT EXISTS resource_categories (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(80) NOT NULL UNIQUE,
    description  TEXT
);

CREATE TABLE IF NOT EXISTS resources (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id           BIGINT NOT NULL REFERENCES resource_categories(id),
    name                  VARCHAR(120) NOT NULL,
    description           TEXT,
    resource_type         VARCHAR(20)  NOT NULL,              -- SPACE | EQUIPMENT
    location              VARCHAR(160),
    capacity              INTEGER,                            -- personas (solo espacios)
    quantity              INTEGER      NOT NULL DEFAULT 1,    -- unidades disponibles (equipos)
    open_time             TIME         NOT NULL DEFAULT '07:00',
    close_time            TIME         NOT NULL DEFAULT '20:00',
    max_duration_minutes  INTEGER      NOT NULL DEFAULT 120,
    requires_approval     BOOLEAN      NOT NULL DEFAULT FALSE,
    state                 VARCHAR(20)  NOT NULL DEFAULT 'AVAILABLE', -- AVAILABLE | MAINTENANCE | INACTIVE
    image_url             VARCHAR(255),
    created_at            TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS resources_category_idx ON resources (category_id);

CREATE TABLE IF NOT EXISTS resource_images (
    resource_id  BIGINT PRIMARY KEY REFERENCES resources(id) ON DELETE CASCADE,
    content_type VARCHAR(50) NOT NULL,
    image_data   BYTEA NOT NULL
);

CREATE TABLE IF NOT EXISTS reservations (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id BIGINT NOT NULL REFERENCES resources(id),
    user_id     BIGINT NOT NULL REFERENCES users(id),
    start_time  TIMESTAMP NOT NULL,
    end_time    TIMESTAMP NOT NULL,
    quantity    INTEGER   NOT NULL DEFAULT 1,
    attendees   INTEGER,
    notes       VARCHAR(500),
    status      VARCHAR(20) NOT NULL,        -- PENDING | CONFIRMED | CANCELLED | REJECTED | COMPLETED
    channel     VARCHAR(10) NOT NULL,        -- WEB | AGENT
    created_at  TIMESTAMP   NOT NULL DEFAULT now(),
    CHECK (end_time > start_time)
);
CREATE INDEX IF NOT EXISTS reservations_resource_time_idx ON reservations (resource_id, start_time, end_time);
CREATE INDEX IF NOT EXISTS reservations_user_idx          ON reservations (user_id);

-- Auditoría del agente de IA (qué se le pidió, qué herramientas usó, qué respondió)
CREATE TABLE IF NOT EXISTS agent_interactions (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL REFERENCES users(id),
    user_message   TEXT NOT NULL,
    agent_reply    TEXT,
    tools_used     VARCHAR(500),
    created_at     TIMESTAMP NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS agent_interactions_user_idx ON agent_interactions (user_id, created_at);

